const uint8_t *sr_font_glyph(char ch) {
  if (ch < 32 || ch > 126) ch = '?';
  return k_font[ch - 32];
}

void sr_font_cell(char ch, int *cx, int *cy) {
  if (ch < 32 || ch > 126) ch = '?';
  int i = ch - 32;
  *cx = (i % 16) * 8;
  *cy = (i / 16) * 8;
}
